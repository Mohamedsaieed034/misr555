        function pushToHistoryLog(actionText) {
            const now = new Date();
            const timeStr = now.toLocaleDateString('ar-EG') + ' ' + now.toLocaleTimeString('ar-EG', {hour:'2-digit', minute:'2-digit', second:'2-digit'});
            const userSign = currentUser ? currentUser.fullname : "زائر";
            systemHistory.unshift({ timestamp: timeStr, user: userSign, text: actionText });
            if(systemHistory.length > 50) systemHistory.pop();
            renderHistoryLogUI();
            if (authToken) {
                apiCall('/api/history', 'POST', { timestamp: timeStr, user: userSign, text: actionText }).catch(() => {});
            }
        }

