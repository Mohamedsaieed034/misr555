let currentLang = localStorage.getItem('appLang') || 'ar';

function t(key) {
    if (!I18N[key]) return key;
    return I18N[key][currentLang] || I18N[key]['ar'] || key;
}

function roleLabel(role) {
    if (role === 'مدير') return t('role_manager_short');
    if (role === 'دكتور') return t('role_doctor_short');
    return t('role_student_short');
}

function applyLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('appLang', lang);
    document.documentElement.setAttribute('lang', lang === 'ar' ? 'ar' : 'en');
    document.documentElement.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');

    const titleTag = document.getElementById('page-title-tag');
    if (titleTag) titleTag.innerText = t('page_title');

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (I18N[key]) el.textContent = I18N[key][lang] || I18N[key]['ar'];
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
        const key = el.getAttribute('data-i18n-ph');
        if (I18N[key]) el.placeholder = I18N[key][lang] || I18N[key]['ar'];
    });

    const langBtn = document.getElementById('lang-toggle-btn');
    if (langBtn) langBtn.innerHTML = `<i class="fa-solid fa-globe"></i> ${lang === 'ar' ? 'EN' : 'AR'}`;

    // إعادة رسم العناصر الديناميكية التي تعرض نصوصاً ثابتة داخل الجافاسكريبت
    if (typeof currentUser !== 'undefined' && currentUser) {
        const disp = document.getElementById('logged-user-display');
        if (disp) disp.innerText = `${t('logged_user_prefix')}: ${currentUser.fullname} (${roleLabel(currentUser.role)})`;
    }
    if (typeof renderUsersTable === 'function' && document.getElementById('users-table-body')) {
        try { renderUsersTable(); } catch(e) {}
    }
}

