        // ================== نظام توليد الأسئلة المستقل والمتوافق بدون تكرارات ==================
        function startInsuranceQuizOnly(quizType) {
            activeQuizType = quizType;
            currentQuizData = [];

            if (quizType === 'insurance') {
                if(!insuranceSettings.companies || insuranceSettings.companies.length < 2) {
                    return alert("الرجاء إضافة شركتي تأمين على الأقل بالسيستم لضمان توليد خيارات متوافقة بدون تكرار.");
                }

                for (let i = 0; i < 25; i++) {
                    let randomComp = insuranceSettings.companies[Math.floor(Math.random() * insuranceSettings.companies.length)];
                    let otherComps = insuranceSettings.companies.filter(c => c !== randomComp);
                    let qTypes = ['duration', 'attachments', 'validity', 'ext'];
                    let chosenType = qTypes[Math.floor(Math.random() * qTypes.length)];
                    let question = ""; let correctAns = ""; let fieldKey = "";
                    
                    if(chosenType === 'duration') {
                        question = `ما هي مدة الصرف المقررة في حالة عدم تحديدها لشركة: (${randomComp})؟`;
                        correctAns = insuranceSettings.duration[randomComp] || "غير محدد لعدم الإدخال بالسيستم"; fieldKey = 'duration';
                    } else if(chosenType === 'attachments') {
                        question = `ما هي المستندات المطلوب إرفاقها إلزامياً لمطالبة شركة: (${randomComp})؟`;
                        correctAns = insuranceSettings.attachments[randomComp] || "غير محدد لعدم الإدخال بالسيستم"; fieldKey = 'attachments';
                    } else if(chosenType === 'validity') {
                        question = `ما هي صلاحية الروشتة أو النموذج لشركة: (${randomComp})؟`;
                        correctAns = insuranceSettings.validity[randomComp] || "غير محدد لعدم الإدخال بالسيستم"; fieldKey = 'validity';
                    } else {
                        question = `ما هي سياسة وقواعد قبول الروشتات الخارجية لشركة: (${randomComp})؟`;
                        correctAns = insuranceSettings.extPrescriptions[randomComp] || "غير محدد لعدم الإدخال بالسيستم"; fieldKey = 'extPrescriptions';
                    }

                    // تجميع الخيارات الخاطئة حصرياً من نفس عمود السؤال لمنع نصوص فروع التعاقد الأجنبية
                    let wrongAnsSet = new Set();
                    otherComps.forEach(oc => { 
                        let val = insuranceSettings[fieldKey] ? insuranceSettings[fieldKey][oc] : null;
                        if(val && val.trim() !== "" && val !== correctAns) {
                            wrongAnsSet.add(val);
                        }
                    });

                    let finalWrongOptions = Array.from(wrongAnsSet).sort(() => 0.5 - Math.random()).slice(0, 3);
                    let options = [correctAns, ...finalWrongOptions].sort(() => 0.5 - Math.random());
                    
                    currentQuizData.push({ question, options, correct: correctAns, type: 'insurance' });
                }

                document.getElementById('ins-quiz-setup-card-ins').classList.add('hidden');
                document.getElementById('ins-quiz-active-card-ins').classList.remove('hidden');
                pushToHistoryLog("بدأ محاولة اختبار التأمين المخصص للشركات");

            } else if (quizType === 'diagnosis') {
                if(!insuranceSettings.diagnoses || insuranceSettings.diagnoses.length < 4) {
                    return alert("الرجاء إضافة 4 تشخيصات طبية على الأقل في الإعدادات لبدء هذا الاختبار.");
                }

                for (let i = 0; i < 25; i++) {
                    let randomDiag = insuranceSettings.diagnoses[Math.floor(Math.random() * insuranceSettings.diagnoses.length)];
                    let askInArabic = Math.random() > 0.5;
                    let question = ""; let correctAns = ""; let isArToEn = true;

                    if (askInArabic) {
                        question = `ما هو المصطلح الطبي المقابل باللغة الإنجليزية للتشخيص التالي: (${randomDiag.ar})؟`;
                        correctAns = randomDiag.en; isArToEn = true;
                    } else {
                        question = `ما هو المعنى بالعربية للمصطلح الطبي أو التشخيص التالي: (${randomDiag.en})؟`;
                        correctAns = randomDiag.ar; isArToEn = false;
                    }

                    let wrongOptionsSet = new Set();
                    let safeguardCounter = 0;
                    
                    while (wrongOptionsSet.size < 3 && safeguardCounter < 100) {
                        safeguardCounter++;
                        let candidate = insuranceSettings.diagnoses[Math.floor(Math.random() * insuranceSettings.diagnoses.length)];
                        
                        if (isArToEn) {
                            if (candidate.en !== correctAns && candidate.ar !== randomDiag.ar) wrongOptionsSet.add(candidate.en);
                        } else {
                            if (candidate.ar !== correctAns && candidate.en !== randomDiag.en) wrongOptionsSet.add(candidate.ar);
                        }
                    }

                    let options = [correctAns, ...Array.from(wrongOptionsSet)].sort(() => 0.5 - Math.random());
                    currentQuizData.push({ question, options, correct: correctAns, type: 'diagnosis' });
                }

                document.getElementById('ins-quiz-setup-card-diag').classList.add('hidden');
                document.getElementById('ins-quiz-active-card-diag').classList.remove('hidden');
                pushToHistoryLog("بدأ محاولة اختبار التشخيصات الطبية الأساسية");
            }

            currentQuestionIndex = 0; quizScore = 0;
            loadInsuranceQuestion();
        }

