        function startLevelQuiz(levelNum, status) {
            if(status === 'locked') return alert("هذه المرحلة التدريبية مغلقة بالنسبة لحسابك حالياً.");
            if(!allStagesMeds[levelNum] || allStagesMeds[levelNum].length === 0) return alert("لا توجد قاعدة بيانات مرفوعة لهذه المرحلة.");
            selectedLevelNum = levelNum; let pool = allStagesMeds[levelNum];
            let shuffled = [...pool].sort(() => 0.5 - Math.random()).slice(0, Math.min(25, pool.length));

            currentQuizData = shuffled.map(med => {
                const type = Math.random() > 0.5 ? 'active' : 'use'; let question = ""; let correct = ""; let wrongs = [];
                if(type === 'active') {
                    question = `ما هي المادة الفعالة للدواء: (${med['اسم الدواء (Name)']})؟`; correct = med['المادة الفعالة (Active ingredient)'] || "غير محدد";
                    wrongs = pool.map(m => m['المادة الفعالة (Active ingredient)']).filter(a => a !== correct && a);
                } else {
                    question = `ما هو الاستخدام الطبي للدواء: (${med['اسم الدواء (Name)']})؟`; correct = med['الاستخدامات الطبية (Uses)'] || "غير محدد";
                    wrongs = pool.map(m => m['الاستخدامات الطبية (Uses)']).filter(a => a !== correct && a);
                }
                wrongs = [...new Set(wrongs)].sort(() => 0.5 - Math.random()).slice(0, 3);
                let options = [...new Set([correct, ...wrongs])].sort(() => 0.5 - Math.random());
                while(options.length < 4) options.push("بديل علمي أخر"); return { question, options, correct };
            });
            currentQuestionIndex = 0; quizScore = 0;
            document.getElementById('quiz-setup-card').classList.add('hidden'); document.getElementById('quiz-active-card').classList.remove('hidden');
            pushToHistoryLog(`بدأ اختبار الأدوية للمرحلة: ${levelNum}`); loadQuestion();
        }

